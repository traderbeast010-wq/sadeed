#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
المدقّق — الاستدعاء الوحيد للنموذج في المسار الأساسي.

يأخذ بنداً واحداً + المواد المسترجَعة له، ويعيد حكماً مُنمّطاً.
كل ما عدا هذه الخطوة في الوكيل كودٌ حتميّ بلا نموذج.

البرومبت مبنيّ على قياس فعلي لا تخمين:
  • القاعدة 9 أُضيفت بعد أن أعاد النموذج «مخالف» مستشهداً بمادة صحيحة لكنها
    خارج الموضوع، ٣ مرّات من ٣. كلمة «موضوع» هي ما أصلحها.
  • reasoning محدود بجملة: المعالجة المسبقة 29 توكن/ث والتوليد 9.3، فكل
    توكن زائد يُدفع ثمنه مرّتين.
"""

VERDICTS = ("مخالف", "ناقص", "سليم", "لا مادة ذات صلة")

SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {"type": "string", "enum": list(VERDICTS)},
        "article_numbers": {"type": "array", "items": {"type": "integer"}},
        "reasoning": {"type": "string"},
        "confidence": {"type": "number"},
    },
    "required": ["verdict", "article_numbers", "reasoning", "confidence"],
    "additionalProperties": False,
}

SYSTEM = """أنت مدقّق قانوني آليّ متخصّص في عقود العمل في سلطنة عُمان.
مهمّتك: الحكم على بند واحد بالاستناد الحصريّ إلى المواد القانونية المعطاة لك.

قواعد ملزمة لا تُخالَف:
1. استخدم المواد المعطاة فقط. ممنوع منعاً باتاً استخدام أي معرفة قانونية من خارجها.
2. إن لم تجد في المواد المعطاة سنداً صريحاً، أرجِع الحكم "لا مادة ذات صلة".
3. ممنوع اختراع رقم مادة أو نصّ مادة غير موجود فيما أُعطي لك.
4. الحكم واحد من أربعة فقط: مخالف | ناقص | سليم | لا مادة ذات صلة
   - مخالف: البند يناقض ما تنصّ عليه مادة معطاة.
   - ناقص: البند يتناول موضوع مادة معطاة لكنه يغفل شرطاً توجبه.
   - سليم: البند متوافق مع مادة معطاة تتناول موضوعه.
   - لا مادة ذات صلة: لا توجد مادة معطاة تتناول موضوع البند.
5. إذا كان الحكم "مخالف" أو "ناقص" أو "سليم" فاذكر رقم المادة في article_numbers.
   وإن تعدّدت القوانين المعطاة، فاذكر اسم القانون في reasoning مع رقم المادة.
6. إذا كان الحكم "لا مادة ذات صلة" فاترك article_numbers فارغة.
7. اجعل reasoning جملة واحدة موجزة بالعربية.
8. أعد JSON فقط.
9. إن أشار البند إلى قانون أو نظام دولة أخرى، فهذا وحده لا يعني أنه مخالف.
   احكم فقط بناء على ما تنصّ عليه المواد المعطاة لك. وإن لم تتناول أي مادة
   معطاة موضوع البند، فالحكم "لا مادة ذات صلة"."""


def build_user_message(clause: str, hits) -> str:
    """
    يصوغ رسالة المستخدم — أوجز صياغة ممكنة لتوفير المعالجة المسبقة.

    مع كوربوس متعدّد القوانين، «المادة (70)» وحدها ملتبسة: قد تكون من
    قانون العمل أو من قانون آخر. فنُلحق اسم القانون **حين يتعدّد المصدر
    فقط** — إلحاقه دائماً يهدر توكنات في الحالة الشائعة (قانون واحد).
    """
    multi = len({h.get("law_id") for h in hits}) > 1
    if multi:
        articles = "\n".join(
            f"[{h.get('law_name', '')} — المادة {h['article_no']}] {h['text']}"
            for h in hits)
    else:
        articles = "\n".join(
            f"[المادة {h['article_no']}] {h['text']}" for h in hits)
    return (f"### المواد القانونية المتاحة\n{articles}\n\n"
            f"### البند محلّ التدقيق\n«{clause}»\n\n"
            f"أصدر حكمك الآن بصيغة JSON.")


def validate_clause(server, clause: str, hits, max_tokens: int = 250):
    """
    يعيد (الحكم الخام كـ dict أو None، توقيتات الخادم).
    التحقّق والتصحيح مسؤولية agent/guard.py لا هذه الدالة.
    """
    import json
    raw, timings = server.chat(
        SYSTEM, build_user_message(clause, hits),
        schema=SCHEMA, max_tokens=max_tokens, temperature=0.0,
    )
    try:
        return json.loads(raw), timings
    except Exception:
        return None, timings
